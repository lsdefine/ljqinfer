def build_routed_down_cache(engine) -> None:
    """Materialize persistent exact-LUT Q8 Down rows before decode graph capture."""
    if getattr(engine, "_routed_down_cache_ready", False):
        return
    keepalive = []
    for rank in range(len(engine.rt.devices)):
        torch.cuda.set_device(rank)
        rank_keepalive = []
        for layer, expert_tuple in ROUTED_DOWN_CACHE_TOP24.items():
            moe = engine.w.layers[layer].ffn
            expert_ids = torch.tensor(expert_tuple, device=rank, dtype=torch.int64)
            cache = K.down_cache.dequant_selected(
                moe.down_exps[rank], expert_ids, 256
            ).reshape(ROUTED_DOWN_CACHE_K, 6144, 288).contiguous()
            expert_to_slot = torch.full((256,), -1, device=rank, dtype=torch.int32)
            expert_to_slot[expert_ids] = torch.arange(
                ROUTED_DOWN_CACHE_K, device=rank, dtype=torch.int32)
            if not hasattr(moe, "down_cache"):
                moe.down_cache = [None] * len(engine.rt.devices)
                moe.down_cache_map = [None] * len(engine.rt.devices)
            moe.down_cache[rank] = cache
            moe.down_cache_map[rank] = expert_to_slot
            rank_keepalive.append((cache, expert_to_slot))
        torch.cuda.synchronize(rank)
        keepalive.append(rank_keepalive)
    engine._routed_down_cache_keepalive = keepalive
    engine._routed_down_cache_ready = True
    gib = sum(cache.nbytes + mapping.nbytes for cache, mapping in keepalive[0]) / 2**30
    print(f"[startup] routed Down cache ready K={ROUTED_DOWN_CACHE_K} per_rank={gib:.3f} GiB", flush=True)
